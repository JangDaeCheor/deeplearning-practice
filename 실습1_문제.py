#     w=0, b=0 자리에서 w 방향과 b 방향의 기울기를 구해 출력하세요.
#       기울기 = (오른쪽 손실 - 왼쪽 손실) / (오른쪽과 왼쪽 사이 거리)
#       살짝 미는 폭 h 는 0.0001 로 하세요.
