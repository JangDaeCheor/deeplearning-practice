# TODO: 여기에 코드를 쓰세요
def 경사하강(lr=0.1, epochs=300):
    w, b = 0.0, 0.0

    for _ in range(epochs):
        # 같은 w, b 위치에서 두 기울기를 모두 구한 뒤 동시에 갱신한다.
        w_grad = (L(w + h, b) - L(w - h, b)) / (2 * h)
        b_grad = (L(w, b + h) - L(w, b - h)) / (2 * h)
        w = w - lr * w_grad
        b = b - lr * b_grad

    return w, b


w, b = 경사하강()
