# TODO: 여기에 코드를 쓰세요
예측 = w * z + b
못맞힌만큼 = np.sum((y - 예측) ** 2)
평균으로찍은만큼 = np.sum((y - y.mean()) ** 2)
R2 = 1 - 못맞힌만큼 / 평균으로찍은만큼
print(f"\n[B9] R2 = {R2:.4f}")

