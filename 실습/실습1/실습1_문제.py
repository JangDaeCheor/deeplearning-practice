# TODO: 여기에 코드를 쓰세요
def 경사하강(lr=0.1, epochs=300):
    w, b = 0.0, 0.0
    for _ in range(epochs):
        gw = (L(w + h, b) - L(w - h, b)) / (2 * h)
        gb = (L(w, b + h) - L(w, b - h)) / (2 * h)
        w = w - lr * gw
        b = b - lr * gb
    return w, b


w, b = 경사하강()
