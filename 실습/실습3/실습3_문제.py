def sigmoid(z):
    return 1 / (1 + np.exp(-z))


def 확률(Z, w, b):
    return sigmoid(Z @ w + b)


def 손실(Z, y, w, b):
    p = np.clip(확률(Z, w, b), 1e-12, 1 - 1e-12)
    return -np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))


h = 0.0001


def 기울기_밟아보기(Z, y, w, b):
    gw = np.zeros(len(w))
    for j in range(len(w)):
        w1, w2 = w.copy(), w.copy()
        w1[j] += h
        w2[j] -= h
        gw[j] = (손실(Z, y, w1, b) - 손실(Z, y, w2, b)) / (2 * h)
    gb = (손실(Z, y, w, b + h) - 손실(Z, y, w, b - h)) / (2 * h)
    return gw, gb


def 학습(Z, y, lr=0.5, epochs=2000, 보여주기=True):
    w = np.zeros(Z.shape[1])
    b = 0.0
    for epoch in range(epochs):
        gw, gb = 기울기_밟아보기(Z, y, w, b)
        w = w - lr * gw
        b = b - lr * gb
        if 보여주기 and epoch % 400 == 0:
            print(f"    epoch {epoch:4d}  손실 {손실(Z, y, w, b):.4f}")
    return w, b


def 네칸(y, 판정):
    TP = int(((y == 1) & (판정 == 1)).sum())
    FN = int(((y == 1) & (판정 == 0)).sum())
    FP = int(((y == 0) & (판정 == 1)).sum())
    TN = int(((y == 0) & (판정 == 0)).sum())
    return TP, FN, FP, TN


